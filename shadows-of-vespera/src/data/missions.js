export const MISSION_ORDER = Object.values(MISSIONS).sort((a, b) => a.number - b.number).map((m) => m.id);

export function getMission(id) { return MISSIONS[id] || null; }

export function missionsForAct(act) {
  return Object.values(MISSIONS).filter((m) => m.act === act).sort((a, b) => a.number - b.number);
}

export function missionsForDistrict(district) {
  return Object.values(MISSIONS).filter((m) => m.district === district).sort((a, b) => a.number - b.number);
}
